// Get topic for a specific user and day
export function getTopicForUserAndDay(userId: string, date: Date = new Date()): string {
  // Create a deterministic seed from user ID and date
  const dateString = date.toISOString().split('T')[0]; // YYYY-MM-DD
  const seedString = `${userId}-${dateString}`;

  // Simple hash function for deterministic selection
  let hash = 0;
  for (let i = 0; i < seedString.length; i++) {
    const char = seedString.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32-bit integer
  }

  // Ensure positive index
  const index = Math.abs(hash) % ACADEMIC_TOPICS.length;
  return ACADEMIC_TOPICS[index];
}

// Get multiple topics for a user (for assignments)
export function getTopicsForUser(userId: string, count: number = 3, date: Date = new Date()): string[] {
  const topics: string[] = [];
  const usedIndices = new Set<number>();

  // Create base seed from user ID and date
  const dateString = date.toISOString().split('T')[0];
  let baseHash = 0;
  for (let i = 0; i < `${userId}-${dateString}`.length; i++) {
    baseHash = ((baseHash << 5) - baseHash) + `${userId}-${dateString}`.charCodeAt(i);
    baseHash = baseHash & baseHash;
  }

  while (topics.length < count && topics.length < ACADEMIC_TOPICS.length) {
    const seed = baseHash + topics.length;
    const index = Math.abs(seed) % ACADEMIC_TOPICS.length;
    if (!usedIndices.has(index)) {
      usedIndices.add(index);
      topics.push(ACADEMIC_TOPICS[index]);
    }
  }

  return topics;
}
